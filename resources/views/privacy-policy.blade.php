            <h2><span class="n">5.</span>Children's information and photographs</h2>
            <p>Much of our work happens in government schools and villages, so children are often present at our
                activities. We handle their information with particular care:</p>
            <ul>
                <li>We aim to involve children only with the permission of the school and, where appropriate, their
                    parents or guardians. Under the Digital Personal Data Protection Act, 2023, we seek verifiable
                    parental or guardian consent before processing the personal data of a person under 18.</li>
                <li>We do not track, profile or send targeted advertising to children, and we do not use their data in
                    ways likely to harm their wellbeing.</li>
                <li>We avoid publishing children's full names, home addresses or contact details alongside their
                    photographs.</li>
                <li>If you are a parent, guardian or teacher and would like a photograph or record removed, write to us
                    at the address in Section 13 and we will act on it promptly.</li>
                <li>Our website is not directed at children under 18, and we ask that they do not submit personal
                    information through it without a parent or guardian.</li>
            </ul>
        </section>

